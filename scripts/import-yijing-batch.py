def main():
    conn = sqlite3.connect(str(DB))
    c = conn.cursor()
    inserted = 0; skipped = 0
    for num, name, symbol, gua_ci, note in GUAS:
        title = f"易经·{name}"
        existing = c.execute("SELECT COUNT(*) FROM kb_formal WHERE title = ? AND module = 'yijing'", (title,)).fetchone()[0]
        if existing > 0:
            skipped += 1
            continue
        content = f"【易经·{name}】{symbol}\n\n卦辞：{gua_ci}\n\n注解：{note}"
        keywords = f"易经,{name},{symbol},卦辞,六十四卦,周易,{name[0]}"
        eid_val = eid("KB-YJ", content)
        c.execute(
            "INSERT INTO kb_formal (entry_id, module, title, content, keywords, trust_score, access_level, status, created_at) VALUES (?, ?, ?, ?, ?, 0.95, 'public', 'active', datetime('now'))",
            (eid_val, 'yijing', title, content, keywords)
        )
        inserted += 1
    conn.commit()
    try:
        c.execute("INSERT INTO kb_formal_fts(kb_formal_fts) VALUES('rebuild')")
        conn.commit()
    except: pass
    conn.close()
    print(f"易经录入完成: 新增 {inserted} 卦, 跳过 {skipped} 卦(已存在)")

main()
