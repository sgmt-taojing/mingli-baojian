def insert_kb(conn, entry_id, title, content, src_id, category,
              keywords, summary, trust=0.7, confidence=0.7):
    c = conn.cursor()
    c.execute("""
        INSERT OR IGNORE INTO kb_formal
        (entry_id, module, title, content, src_id, category, keywords, summary,
         trust_score, version, promoted_at, promoted_from, reviewed_by,
         hit_count, last_hit, tags, source_ids, confidence,
         access_level, difficulty, status)
        VALUES (?, 'tcm', ?, ?, ?, ?, ?, ?, ?, 'v1', CURRENT_TIMESTAMP,
                'audit-auto', 'audit-auto', 0, NULL, '[]', ?, ?, 'registered',
                'intermediate', 'formal')
    """, (entry_id, title, content, src_id, category,
          json.dumps(keywords, ensure_ascii=False), summary,
          trust, f'["{src_id}"]', confidence))
    return c.rowcount

def ensure_source(conn, src_id, src_type, title, trust=0.7):
    c = conn.cursor()
    c.execute("""INSERT OR IGNORE INTO source_index
        (src_id, src_type, title, trust_score, tags, access_level, module)
        VALUES (?, ?, ?, ?, '[]', 'public', 'tcm')""",
        (src_id, src_type, title, trust))
    conn.commit()

