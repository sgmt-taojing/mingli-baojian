def init_source(conn, src_id, src_type, title, author='', trust_score=0.85):
    try:
        conn.execute("INSERT OR IGNORE INTO source_index (src_id, src_type, title, author, trust_score, created_at) VALUES (?,?,?,?,?,?)",
            (src_id, src_type, title, author, trust_score, datetime.now().isoformat()))
        conn.commit()
    except: pass

def insert_kb(conn, entry_id, module, title, content, src_id, category='R3-中医深耕',
              summary='', keywords=None, confidence=0.85, tags=None):
    conn.execute(
        """INSERT OR IGNORE INTO kb_staging (entry_id, module, title, content, src_id, category, summary, keywords, confidence, tags, access_level, difficulty, status, created_at)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
        (entry_id, module, title, content, src_id, category, summary or title,
         json.dumps(keywords or []), confidence, json.dumps(tags or []),
         'registered', 'intermediate', 'pending', datetime.now().isoformat()))
    conn.commit()

def eid(title, content=''):
    h = hashlib.md5((title + content[:50]).encode('utf-8')).hexdigest()[:8]
    return f"KB-tcm-{h}"

def batch(conn, entries, src_id='SRC-ZHONGYI-20260809'):
    count = 0
    for title, content, kws, tags in entries:
        insert_kb(conn, eid(title, content), 'tcm', title, content, src_id,
                  category='R3-中医深耕', summary=title, keywords=kws, confidence=0.85, tags=tags)
        count += 1
    return count

