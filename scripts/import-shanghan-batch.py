def main():
    conn = sqlite3.connect(str(DB))
    c = conn.cursor()
    inserted = 0; skipped = 0
    for name, indication, text, herbs, effect in SHANGHAN:
        title = f"伤寒论·{name}"
        existing = c.execute("SELECT COUNT(*) FROM kb_formal WHERE title = ?", (title,)).fetchone()[0]
        if existing > 0:
            skipped += 1
            continue
        content = f"【伤寒论·{name}】\n\n主治：{indication}\n\n条文：{text}\n\n组成：{herbs}\n\n功用：{effect}"
        keywords = f"伤寒论,{name},经方,仲景,张仲景,{indication[:10]},{effect[:10]}"
        eid_val = eid("KB-SHL", content)
        c.execute(
            "INSERT INTO kb_formal (entry_id, module, title, content, keywords, trust_score, access_level, status, created_at) VALUES (?, ?, ?, ?, ?, 0.95, 'public', 'active', datetime('now'))",
            (eid_val, 'shanghan-lun', title, content, keywords)
        )
        inserted += 1
    conn.commit()
    try:
        c.execute("INSERT INTO kb_formal_fts(kb_formal_fts) VALUES('rebuild')")
        conn.commit()
    except: pass
    conn.close()
    print(f"伤寒论录入完成: 新增 {inserted} 方, 跳过 {skipped} 方(已存在)")

main()
