def write_all():
    db = sqlite3.connect(DB)
    cur = db.cursor()
    total = 0

    for module, entries in ENTRIES.items():
        written = 0
        for title, content, category, trust in entries:
            h = hashlib.md5(f"{module}:{title}".encode()).hexdigest()[:12]
            eid = f"KB-R484-{module[:4].upper()}-{h}"
            cur.execute("SELECT 1 FROM kb_formal WHERE entry_id=?", (eid,))
            if cur.fetchone(): continue

            src_id = f"SRC-DISTILL-{module.upper()}"
            cur.execute("SELECT src_id FROM source_index WHERE src_id=?", (src_id,))
            if not cur.fetchone():
                cur.execute("INSERT OR IGNORE INTO source_index(src_id,src_type,title,author,trust_score,tags) VALUES(?,'SRC-EXPERT',?,'命理宝鉴蒸馏系统',0.85,?)",
                    (src_id, f'{module} R484蒸馏', json.dumps([module,"distill","r484"])))

            cur.execute("""INSERT INTO kb_formal(entry_id,module,title,content,src_id,category,keywords,summary,confidence,tags,source_ids,status,created_at)
                VALUES(?,?,?,?,?,?,?,?,?,?,?,'formal',datetime('now','localtime'))""",
                (eid, module, title[:200], content, src_id, category,
                 json.dumps([module,category.split('·')[0] if '·' in category else category]),
                 content[:200], trust, json.dumps([module,"r484"]), json.dumps([src_id])))
            written += 1

        db.commit()
        print(f'  {module}: +{written}')
        total += written

    # FTS5 增量同步
    cur.execute("""INSERT OR IGNORE INTO kb_fts5(entry_id,module,title,content,keywords,category)
        SELECT entry_id,module,title,content,keywords,category FROM kb_formal
        WHERE entry_id LIKE 'KB-R484-%'""")
    db.commit()

    print(f'\n总计: +{total} 条')
    print(f'kb_formal: {cur.execute("SELECT COUNT(*) FROM kb_formal").fetchone()[0]}')
    db.close()
    return total

if __name__ == "__main__":
    write_all()
