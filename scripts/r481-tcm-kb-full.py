# promote → formal
rows = cur.execute("""
    SELECT entry_id, module, content, summary, tags, source_ids, category, confidence
    FROM staging_knowledge WHERE entry_id LIKE 'KB-tongue-%' OR entry_id LIKE 'KB-face-%' OR entry_id LIKE 'KB-hand-%'
    AND status='staging'
""").fetchall()

for row in rows:
    eid, mod, content, summary, tags, src, cat, conf = row
    cur.execute("""
        INSERT OR REPLACE INTO formal_knowledge
        (entry_id, module, content, summary, tags, source_ids, category, confidence, status, version, created_at)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, 'formal', 1, ?)
    """, (eid, mod, content, summary, tags, src, cat, conf, now))
    cur.execute("UPDATE staging_knowledge SET status='promoted' WHERE entry_id=?", (eid,))
conn.commit()

# FTS5
fts5_rows = cur.execute("""
    SELECT entry_id, module, summary, content, tags, category
    FROM formal_knowledge WHERE entry_id LIKE 'KB-tongue-%' OR entry_id LIKE 'KB-face-%' OR entry_id LIKE 'KB-hand-%'
""").fetchall()

ok = 0
for row in fts5_rows:
    eid, mod, summary, content, tags, cat = row
    try:
        existing = cur.execute("SELECT 1 FROM kb_fts5 WHERE entry_id=?", (eid,)).fetchone()
        if existing:
            cur.execute("UPDATE kb_fts5 SET module=?, title=?, content=?, keywords=?, category=? WHERE entry_id=?",
                        (mod, summary, content, tags, cat, eid))
        else:
            cur.execute("INSERT INTO kb_fts5 (entry_id, module, title, content, keywords, category) VALUES (?, ?, ?, ?, ?, ?)",
                        (eid, mod, summary, content, tags, cat))
        ok += 1
    except Exception as ex:
        print(f'  ❌ FTS5 {eid[:20]}: {ex}')
conn.commit()

