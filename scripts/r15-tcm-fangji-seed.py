def trust_for(cat):
    return 0.85 if cat in ("SHANGHAN", "JINKUI", "WENBING") else 0.7


def cat_label(cat):
    return {"SHANGHAN": "伤寒论", "JINKUI": "金匮要略", "WENBING": "温病条辨", "LUZONG": "路总实践方"}[cat]


def build_content(title, comp, eff, ind, use, con):
    return f"【{title}】组成：{comp}。功效：{eff}。主治：{ind}。用法：{use}。禁忌：{con}。"


def main():
    if not DB_PATH.exists():
        print(f"ERROR: db not found at {DB_PATH}")
        sys.exit(1)

    conn = sqlite3.connect(str(DB_PATH))
    cur = conn.cursor()

    cur.execute("SELECT COUNT(*) FROM kb_formal WHERE entry_id LIKE 'r15-tcm-fangji-%'")
    existing = cur.fetchone()[0]
    print(f"INFO: r15-tcm-fangji-* 命名空间当前 {existing} 条")

    # 验证 src_id 已存在
    for sid in ("SRC-CLASSIC-SHJ", "SRC-CLASSIC-JG", "SRC-LD-FJ"):
        cur.execute("SELECT COUNT(*) FROM source_index WHERE src_id=?", (sid,))
        if cur.fetchone()[0] == 0:
            print(f"ERROR: src_id {sid} 未注册")
            sys.exit(2)
        else:
            print(f"OK: src_id {sid} 已注册")

    # 批量 INSERT（INSERT...SELECT FROM 模式 + WHERE NOT EXISTS 防重复）
    inserted = 0
    skipped = 0
    for no, title, comp, eff, ind, use, con, cat in ALL:
        entry_id = f"r15-tcm-fangji-{no:03d}"
        src_id = src_for(cat)
        trust = trust_for(cat)
        cat_label_str = cat_label(cat)
        content = build_content(title, comp, eff, ind, use, con)
        keywords = ",".join([title.split("·")[-1] if "·" in title else title, cat_label_str, "经方", "中医方剂"])
        summary = f"{title}：{eff}。主治：{ind[:60]}..."

        # 用 INSERT...SELECT FROM 模式（按 task 要求）。先 NOT EXISTS 检查
        # 这里为了兼容 SQLite，我们改用：先 SELECT 查再 INSERT OR IGNORE
        cur.execute("SELECT 1 FROM kb_formal WHERE entry_id=? LIMIT 1", (entry_id,))
        exists = cur.fetchone() is not None
        if exists:
            skipped += 1
            continue

        # 用 INSERT...SELECT FROM 模式避免 rowcount 不可信（task 要求）
        # SQLite 没有 stored SELECT FROM dual，所以用 VALUES table
        cur.execute("""
            INSERT OR IGNORE INTO kb_formal (
                entry_id, module, title, content, src_id, category, keywords, summary,
                trust_score, version, promoted_from, reviewed_by,
                tags, source_ids, confidence, access_level, difficulty, status
            )
            SELECT
                ? AS entry_id,
                ? AS module,
                ? AS title,
                ? AS content,
                ? AS src_id,
                ? AS category,
                ? AS keywords,
                ? AS summary,
                ? AS trust_score,
                'v1' AS version,
                'r15-classic-seed' AS promoted_from,
                'r15-tcm-fangji-worker' AS reviewed_by,
                '["经方","' || ? || '"]' AS tags,
                '["' || ? || '"]' AS source_ids,
                ? AS confidence,
                'public' AS access_level,
                'intermediate' AS difficulty,
                'formal' AS status
            WHERE NOT EXISTS (SELECT 1 FROM kb_formal WHERE entry_id = ?)
        """, (
            entry_id, "tcm-fangji", title, content, src_id, cat_label_str,
            keywords, summary, trust, cat_label_str, src_id, trust, entry_id
        ))

        # 检查是否真的插入（rowcount 不可信）
        cur.execute("SELECT 1 FROM kb_formal WHERE entry_id=? LIMIT 1", (entry_id,))
        if cur.fetchone() is not None:
            inserted += 1
        else:
            skipped += 1

    conn.commit()

    # 验证
    cur.execute("SELECT COUNT(*) FROM kb_formal WHERE module='tcm-fangji'")
    total = cur.fetchone()[0]
    cur.execute("SELECT COUNT(*) FROM kb_formal WHERE entry_id LIKE 'r15-tcm-fangji-%'")
    new_total = cur.fetchone()[0]

    # 按 src_id 分布
    cur.execute("""
        SELECT src_id, COUNT(*) FROM kb_formal
        WHERE module='tcm-fangji' AND src_id IN ('SRC-CLASSIC-SHJ','SRC-CLASSIC-JG','SRC-LD-FJ')
        GROUP BY src_id
    """)
    dist = cur.fetchall()

    print(f"\n=== RESULT ===")
    print(f"INSERTED: {inserted}")
    print(f"SKIPPED:  {skipped}")
    print(f"total tcm-fangji: {total}")
    print(f"total r15-tcm-fangji-*: {new_total}")
    print(f"distribution: {dist}")
    print(f"达标: {'YES' if total >= 200 else 'NO'}")
    print(f"新增 r15-tcm-fangji ≥118: {'YES' if new_total >= 118 else 'NO'}")

    conn.close()


