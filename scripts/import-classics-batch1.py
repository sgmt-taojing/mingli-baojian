def main():
    conn = sqlite3.connect(str(DB))
    c = conn.cursor()
    inserted = 0
    skipped = 0
    for ch_num, text, note in DDJ:
        title = f"典籍精华·道德经·第{ch_num}章"
        # check existing
        existing = c.execute("SELECT COUNT(*) FROM kb_formal WHERE title = ?", (title,)).fetchone()[0]
        if existing > 0:
            skipped += 1
            continue
        content = f"【道德经·第{ch_num}章】\n\n原文：{text}\n\n注解：{note}"
        content_with_kw = content + f"\n\n关键词：道德经 第{ch_num}章 老子 道家 {'无为' if ch_num in [3,10,37,48,57] else '自然' if ch_num in [5,17,23,25] else '柔弱' if ch_num in [36,43,76,78] else '道'}"
        eid_val = eid("KB-CLSC3", content)
        c.execute(
            "INSERT INTO kb_formal (entry_id, module, title, content, keywords, trust_score, access_level, status, created_at) VALUES (?, ?, ?, ?, ?, 0.95, 'public', 'active', datetime('now'))",
            (eid_val, 'classics', title, content_with_kw, '道德经,老子,道家,道,无为,自然,柔弱')
        )
        inserted += 1
    conn.commit()
    # update FTS
    try:
        c.execute("INSERT INTO kb_formal_fts(kb_formal_fts) VALUES('rebuild')")
        conn.commit()
    except:
        pass
    conn.close()
    print(f"道德经录入完成: 新增 {inserted} 章, 跳过 {skipped} 章(已存在)")

if __name__ == '__main__':
    main()
