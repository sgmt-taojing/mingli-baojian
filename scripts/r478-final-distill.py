def main():
    db = sqlite3.connect(DB_PATH)
    cur = db.cursor()
    
    total_written = 0
    
    for module, entries in POOL.items():
        written = 0
        skipped = 0
        for title, content, category, trust in entries:
            h = hashlib.md5(f"{module}:{title}".encode()).hexdigest()[:12]
            eid = f"KB-DIST-{module.upper()}-{h}"
            
            cur.execute("SELECT 1 FROM kb_formal WHERE entry_id=?", (eid,))
            if cur.fetchone():
                skipped += 1; continue
            cur.execute("SELECT 1 FROM kb_staging WHERE entry_id=?", (eid,))
            if cur.fetchone():
                skipped += 1; continue
            
            src_id = f"SRC-DISTILL-{module.upper()}"
            cur.execute("SELECT src_id FROM source_index WHERE src_id=?", (src_id,))
            if not cur.fetchone():
                cur.execute("INSERT OR IGNORE INTO source_index(src_id,src_type,title,author,trust_score,tags) VALUES(?,?,?,?,?,?)",
                    (src_id, 'SRC-EXPERT', f'{module} R478蒸馏', '命理宝鉴蒸馏系统', 0.85, json.dumps([module,"distill","r478"])))
            
            cur.execute("""INSERT INTO kb_staging(entry_id,module,title,content,src_id,category,keywords,summary,confidence,tags,source_ids,status,created_at)
                VALUES(?,?,?,?,?,?,?,?,?,?,?,'pending',datetime('now','localtime'))""",
                (eid, module, title[:200], content, src_id, category,
                 json.dumps([module, category.split('·')[0] if '·' in category else category]),
                 content[:200], trust, json.dumps([module,"r478"]), json.dumps([src_id])))
            
            if cur.rowcount > 0: written += 1
            else: skipped += 1
        
        # Promote to formal
        cur.execute("""INSERT INTO kb_formal(entry_id,module,title,content,src_id,category,keywords,summary,confidence,tags,source_ids,status,created_at)
            SELECT entry_id,module,title,content,src_id,category,keywords,summary,confidence,tags,source_ids,'formal',created_at
            FROM kb_staging WHERE src_id=? AND status='pending' AND entry_id NOT IN (SELECT entry_id FROM kb_formal)""",
            (f'SRC-DISTILL-{module.upper()}',))
        promoted = cur.rowcount
        cur.execute("UPDATE kb_staging SET status='promoted' WHERE src_id=? AND status='pending'",
            (f'SRC-DISTILL-{module.upper()}',))
        
        db.commit()
        print(f'  ✅ {module}: written={written}, skipped={skipped}, promoted={promoted}')
        total_written += written
    
    print(f'\n=== 总计 ===')
    print(f'written={total_written}')
    print(f'kb_formal: {cur.execute("SELECT COUNT(*) FROM kb_formal").fetchone()[0]}')
    pr = cur.execute("SELECT COUNT(*) FROM kb_staging WHERE status='promoted'").fetchone()[0]; print(f'kb_staging: {pr} promoted')
    
    # FTS5 重建
    cur.execute("DELETE FROM kb_fts5")
    cur.execute("""INSERT INTO kb_fts5(entry_id,module,title,content,keywords,category)
        SELECT entry_id,module,title,content,keywords,category FROM kb_formal WHERE status='formal' OR status IS NULL""")
    db.commit()
    fts5_count = cur.execute("SELECT COUNT(*) FROM kb_fts5").fetchone()[0]; print(f'kb_fts5: {fts5_count}')
    
    db.close()

if __name__ == "__main__":
    main()
