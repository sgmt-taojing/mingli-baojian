def main():
    conn = sqlite3.connect(DB, timeout=30)
    conn.execute('PRAGMA busy_timeout=30000')
    cur = conn.cursor()
    now = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    lib_fps = set()
    for (c,) in cur.execute("SELECT CAST(content AS TEXT) FROM kb_formal"):
        if c: lib_fps.add(hashlib.sha256(str(c).strip().encode('utf-8','ignore')).hexdigest())
    inserted, skipped = 0, []
    for title, content, src in SEEDS:
        full = f"{content}（出处：{src}）"
        if len(full) < 60:
            skipped.append((title[:20], '短<60')); continue
        if not any(a in full for a in ANCHOR):
            skipped.append((title[:20], '无锚点')); continue
        fp = hashlib.sha256(full.strip().encode('utf-8','ignore')).hexdigest()
        if fp in lib_fps:
            skipped.append((title[:20], '指纹重复')); continue
        h = hashlib.sha256(f"bazi|{full}".encode()).hexdigest()[:12]
        try:
            cur.execute("""INSERT INTO kb_formal (entry_id, module, title, content, src_id, category,
                keywords, summary, trust_score, version, promoted_at, promoted_from)
                VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)""",
                (f'KB-BZ1-{h}', 'bazi', title, full, SRC, 'bazi',
                 json.dumps(['bazi','子平真诠','格局','用神'], ensure_ascii=False),
                 title[:80], 0.85, 1, now, 't1-batch1', 'formal'))
            inserted += 1; lib_fps.add(fp)
        except sqlite3.Error as e:
            skipped.append((title[:20], f'DB:{e}'))
    conn.commit()
    print(f'T1 第一批入库 {inserted} / 跳过 {len(skipped)}')
    for s in skipped: print('  -', s)
    conn.close()

if __name__ == '__main__':
    main()
