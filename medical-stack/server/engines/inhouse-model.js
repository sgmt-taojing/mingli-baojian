// R514: 多轮追问 - 推荐下一个最有区分力的症状
function _suggestNextSymptom(complaint, asked = []) {
  const syndromes = COMPLAINT_TO_SYNDROMES[complaint] || [];
  if (syndromes.length === 0) {
    return { next: null, reason: '主症暂无候选证型, 可结束问诊' };
  }
  const askedSet = new Set(asked);
  const syndromeSet = new Set(syndromes.map(s => typeof s === 'string' ? s : s.syndrome));
  // 优先级 1: SYMPTOM_TO_SYNDROMES 反查 (主推)
  const candidates = [];
  for (const [symptom, synMap] of Object.entries(SYMPTOM_TO_SYNDROMES)) {
    if (askedSet.has(symptom)) continue;
    if (!synMap || typeof synMap !== 'object') continue;
    const hits = Object.keys(synMap).filter(s => syndromeSet.has(s));
    if (hits.length > 0) {
      const totalWeight = hits.reduce((sum, s) => sum + synMap[s], 0);
      candidates.push({ symptom, syndromes: hits, count: hits.length, weight: totalWeight, source: 'kb' });
    }
  }
  // 优先级 2: 如果反查为空, 从 COMPLAINT_TO_SYNDROMES 自带特征 (summary + score 高的症状)
  if (candidates.length === 0) {
    for (const s of syndromes) {
      if (s.feature) {
        const key = s.feature;
        if (!askedSet.has(key)) {
          candidates.push({ symptom: key, syndromes: [s.syndrome], count: 1, weight: s.score || 0.5, source: 'complaint_features' });
        }
      }
    }
  }
  if (candidates.length === 0) {
    return { next: null, reason: '已问完所有候选症状, 可结束问诊' };
  }
  candidates.sort((a, b) => b.weight - a.weight);
  const top = candidates[0];
  return {
    next: top.symptom,
    reason: '该症状可区分 ' + top.count + ' 个证型: ' + top.syndromes.join('、'),
    options: candidates.slice(0, 5).map(c => ({ symptom: c.symptom, syndromes_count: c.count, weight: c.weight, covers: c.syndromes, source: c.source })),
    remaining: candidates.length
  };
}


