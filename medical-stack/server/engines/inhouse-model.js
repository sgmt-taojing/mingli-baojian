// 计算体质与方剂的相宜度
function _checkConstitutionAffinity(constitution, formulaName) {
  if (!constitution) return null;
  const cat = _FORMULA_CATEGORY[formulaName];
  if (!cat) return null;
  const aff = _CONSTITUTION_FORMULA_AFFINITY[constitution]?.[cat];
  if (aff === undefined) return null;
  let level = 'neutral';
  if (aff >= 0.85) level = 'strong_fit';
  else if (aff >= 0.7) level = 'fit';
  else if (aff < 0.4) level = 'caution';
  return { category: cat, affinity: aff, level, constitution };
}

// 检查特殊人群忌方
function _checkPopulationContraindication(group, formulaName, herbList = []) {
  // 优先用真实药材列表；若 herbList 为空（FORMULA_TO_HERBS 缺失该方），
  // 从 formulaName 中提取已知风险药材名进行兜底匹配
  const RISK_HERBS = ['附子','大黄','麻黄','细辛','雄黄','朱砂','雷公藤','肉桂','吴茱萸','麝香','水蛭','三棱','莪术','斑蝥','牛膝','半夏','天南星','人参'];
  let allText = formulaName;
  if (herbList && herbList.length) {
    allText += ' ' + herbList.join(' ');
  } else {
    // 兜底：从 formulaName 中提取风险药材
    const found = RISK_HERBS.filter(h => formulaName.includes(h));
    if (found.length) allText += ' ' + found.join(' ');
  }
  const alerts = [];
  for (const rule of _POPULATION_CONTRAINDICATIONS) {
    if (rule.group === group && rule.pattern.test(allText)) {
      alerts.push({ group, level: rule.level, formula: formulaName, reason: rule.reason });
    }
  }
  return alerts;
}

