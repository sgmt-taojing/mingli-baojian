// 七诊融合诊断
function sevenDiagnosisFusion(primaryResult, earSigns, infraredSigns, smellVoiceSigns) {
  const bonus = {};
  
  // 耳诊加权
  if (earSigns && earSigns.length) {
    earSigns.forEach(sign => {
      const mapping = EAR_DIAGNOSIS_MAP[sign];
      if (mapping) {
        Object.entries(mapping).forEach(([syndrome, w]) => {
          bonus[syndrome] = (bonus[syndrome] || 0) + w * 0.15;
        });
      }
    });
  }
  
  // 红外面诊加权
  if (infraredSigns && infraredSigns.length) {
    infraredSigns.forEach(sign => {
      const mapping = INFRARED_FACE_MAP[sign];
      if (mapping) {
        Object.entries(mapping).forEach(([syndrome, w]) => {
          bonus[syndrome] = (bonus[syndrome] || 0) + w * 0.15;
        });
      }
    });
  }
  
  // 闻诊加权
  if (smellVoiceSigns && smellVoiceSigns.length) {
    smellVoiceSigns.forEach(sign => {
      const mapping = SMELL_VOICE_MAP[sign];
      if (mapping) {
        Object.entries(mapping).forEach(([syndrome, w]) => {
          bonus[syndrome] = (bonus[syndrome] || 0) + w * 0.12;
        });
      }
    });
  }
  
  // 合并加分
  const updated = primaryResult.differential.map(item => ({
    ...item,
    score: Math.min(0.98, item.score + (bonus[item.syndrome] || 0)),
    confidence: Math.min(0.98, item.confidence + (bonus[item.syndrome] || 0) * 0.8)
  }));
  
  updated.sort((a, b) => b.score - a.score);
  
  return {
    ...primaryResult,
    differential: updated,
    primary_syndrome: updated[0] || primaryResult.primary_syndrome,
    seven_diagnosis_bonus: bonus,
    ear_signs: earSigns || [],
    infrared_signs: infraredSigns || [],
    smell_voice_signs: smellVoiceSigns || []
  };
}

